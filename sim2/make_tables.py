def table_e4():
    d = load("merged_expAB_robustness.json")
    if d is None:
        return
    from common import bootstrap_mean_ci
    lines = ["\\begin{table}[h]", "\\centering\\scriptsize",
             "\\caption{S3 attribution and $\\varepsilon=0$ bias (E4), Brier units. Estimates are means over "
             f"{d['parameters']['seeds_per_row']} independent seeds with 95\\% bootstrap intervals. The union-graph bias at "
             "$n=" + f"{d['parameters']['n_scaling'][-1]:,}".replace(",", "{,}") + "$ is relative to its oracle Shapley target.}",
             "\\label{tab:robustness}", "\\resizebox{\\columnwidth}{!}{%", "\\begin{tabular}{lrrrr}", "\\toprule",
             "Setting & True $\\Delta R$ & Monitor $Y|X$ & Proposed $\\pi$ & Union bias\\\\", "\\midrule"]
    for st in d["settings"]:
        s3 = next(r for r in st["A"] if r["scenario"] == "S3")
        naive = [r["naive2_est"]["Ygx"] for r in s3["runs"]]
        prop = [r["E3_rollout"]["pi"] for r in s3["runs"]]
        big = st["n_scaling_eps_zero"][-1]
        bias = np.array(big["runs"]) - big["truth_shapley_pi"]
        def c(v):
            lo, hi = bootstrap_mean_ci(v)
            return f"{np.mean(v):.4f} [{lo:.4f}, {hi:.4f}]".replace("-", "$-$")
        label = f"$d={st['d']}$, {'nonlinear' if st['nonlinear_outcome'] else 'linear'}"
        lines.append(f"{label} & {s3['truth_policy_contrast']['dR']:.4f} & {c(naive)} & {c(prop)} & {c(bias)}\\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "}", "\\end{table}"]
    write("e4_robustness", lines)


