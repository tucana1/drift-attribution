def table_e1():
    d = load("merged_expE1.json")
    if d is None:
        return
    rows = (("never", "Never refit"), ("always", "Always refit (naive)"),
            ("exo_proposed", "Refit if exogenous share $>1/2$"),
            ("outcome_proposed", "Refit if outcome share $>1/2$"),
            ("outcome_monitor", "\\quad same, monitor (no action log)"),
            ("refit_untreated", "Reference: refit on $A{=}0$"))
    worst = {w["rule"]: w for w in d["worst_case"] if w["threshold_rule"] == "fixed"}
    half_widths = [max(t["events_averted_pp"]["ci95"][1] - t["events_averted_pp"]["mean"],
                       t["events_averted_pp"]["mean"] - t["events_averted_pp"]["ci95"][0])
                   for t in d["table"] if t["threshold_rule"] == "fixed"]
    reps = d["parameters"]["reps"]
    lines = [
        "\\begin{table}[t]", "\\centering\\scriptsize", "\\setlength{\\tabcolsep}{3pt}",
        "\\caption{Keep-or-refit rules (E1), fixed alert threshold. Events averted against standard care in "
        "the window after the decision (percentage points), mean over "
        f"{reps} independent replicates per scenario; 95\\% bootstrap intervals are within "
        f"$\\pm{max(half_widths):.2f}$. Percentages give how often a rule refits. Regret is measured "
        "against the better of keeping and naive refitting in each replicate; a negative value beats both.}",
        "\\label{tab:decision}",
        "\\resizebox{\\columnwidth}{!}{%", "\\begin{tabular}{lrrrrrr}", "\\toprule",
        "Rule & S1 & S2 & S3 & S4 & \\multicolumn{2}{c}{Regret}\\\\",
        "& & & & & mean & worst\\\\", "\\midrule"]
    for rule, label in rows:
        cells = []
        for sc in ("S1", "S2", "S3", "S4"):
            e = next(t for t in d["table"] if t["threshold_rule"] == "fixed" and t["scenario"] == sc and t["rule"] == rule)
            cell = fmt(e["events_averted_pp"]["mean"], 1)
            if rule in ("exo_proposed", "outcome_proposed", "outcome_monitor"):
                cell += f" ({100 * e['retrain_fraction']:.0f}\\%)"
            cells.append(cell)
        w = worst[rule]
        lines.append(f"{label} & " + " & ".join(cells) + f" & {fmt(w['mean_regret_pp'], 1)} & {fmt(w['max_mean_regret_pp'], 1)}\\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "}", "\\end{table}"]
    write("e1_decision", lines)

    # appendix: rate-held threshold and harm sensitivity
    lines = ["\\begin{table}[h]", "\\centering\\scriptsize", "\\setlength{\\tabcolsep}{3pt}",
             "\\caption{E1 under the rate-held threshold (events averted, pp) and harm sensitivity under the fixed "
             "threshold: net events averted when each extra treatment of a patient whose untreated outcome is 0 "
             "costs $h$ events.}", "\\label{tab:decision-app}",
             "\\begin{tabular}{llrrrr}", "\\toprule", "Threshold & Rule & S1 & S2 & S3 & S4\\\\", "\\midrule"]
    for rule, label in rows:
        cells = [fmt(next(t for t in d["table"] if t["threshold_rule"] == "rate" and t["scenario"] == sc
                          and t["rule"] == rule)["events_averted_pp"]["mean"], 2) for sc in ("S1", "S2", "S3", "S4")]
        lines.append(f"rate-held & {label} & " + " & ".join(cells) + "\\\\")
    lines.append("\\midrule")
    for h in (0.1, 0.2):
        for rule, label in rows:
            cells = [fmt(next(x for x in d["harm_sensitivity"] if x["threshold_rule"] == "fixed" and x["scenario"] == sc
                              and x["rule"] == rule and x["harm_per_unnecessary_treatment"] == h)
                         ["net_events_averted_pp"]["mean"], 1) for sc in ("S1", "S2", "S3", "S4")]
            lines.append(f"fixed, $h={h:g}$ & {label} & " + " & ".join(cells) + "\\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    write("e1_decision_appendix", lines)


