def table_e5():
    d = load("merged_expG2.json")
    if d is None:
        return
    names = {"random_order_common_trend": "Random, common", "random_order_site_trend": "Random, site-specific",
             "correlated_order_common_trend": "Linked, common", "correlated_order_site_trend": "Linked, site-specific"}
    cols = (("retro", "Retro."), ("x_endogenous_mean", "Induced"), ("x_exogenous_mean", "Exog."),
            ("x_endogenous_loss", "Induced"), ("x_exogenous_loss", "Exog."),
            ("x_endogenous_loss_did", "Induced"), ("x_exogenous_loss_did", "Exog."))
    lines = ["\\begin{table*}[t]", "\\centering\\scriptsize",
             "\\caption{Persistent-site stepped wedge (E5): bias as a percentage of the true value, with 95\\% bootstrap "
             f"interval, over {d['parameters']['seeds_per_row']} independent seeds per row. Rollout order is random or linked "
             "to the site characteristic; covariate trends are common or site specific. Retrospective term: crossover "
             "difference in differences. $X$ split in the covariate mean, and on the Brier scale by the plug-in and the "
             "DiD-anchored estimators.}",
             "\\label{tab:sites}", "\\resizebox{\\textwidth}{!}{%", "\\begin{tabular}{lccccccc}", "\\toprule",
             "Rollout order, trend & Retrospective & \\multicolumn{2}{c}{$X$ mean split} & "
             "\\multicolumn{2}{c}{Brier $X$ split, plug-in} & \\multicolumn{2}{c}{Brier $X$ split, DiD-anchored}\\\\",
             "\\cmidrule(lr){3-4}\\cmidrule(lr){5-6}\\cmidrule(lr){7-8}",
             " & " + " & ".join(c[1] for c in cols) + "\\\\", "\\midrule"]
    for row in d["rows"]:
        s = row["summary"]
        cells = []
        for key, _ in cols:
            v = s[key]
            lo, hi = (100 * np.array(v["bias_ci95"]) / v["truth_mean"])
            lo, hi = min(lo, hi), max(lo, hi)
            cells.append(f"{100 * v['relative_bias']:+.1f} [{lo:+.1f}, {hi:+.1f}]".replace("-", "$-$").replace("+", "$+$"))
        lines.append(names[row["setting"]] + " & " + " & ".join(cells) + "\\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "}", "\\end{table*}"]
    write("e5_sites", lines)


